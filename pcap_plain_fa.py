def plain_summary_html(level, score, findings, esc) -> str:
    icon, head, sub = VERDICT.get(level, VERDICT["info"])
    top = findings[:3]
    steps = []
    for f in top:
        steps.append(f'<li><b>{esc(f["title"])}</b><br><span class="muted">{esc(plain_for(f["id"])[2])}</span></li>')
    if not steps:
        steps.append("<li>کار فوری لازم نیست. اگر هنوز نگران هستید، فایل را با ابزارهای دیگر هم بررسی کنید.</li>")
    gloss = "".join(f"<dt>{esc(a)}</dt><dd>{esc(b)}</dd>" for a, b in GLOSSARY)
    return (
        '<section class="verdict-card"><div class="vc-icon">' + icon + '</div><div>'
        f'<h2 class="vc-title">{esc(head)}</h2><p>{esc(sub)}</p>'
        f'<p class="muted">امتیاز ریسک: <b>{score}/100</b> · تعداد هشدار: <b>{len(findings)}</b></p></div></section>'
        '<div class="card"><h3 style="margin-top:0">✅ سه کار اول (به ترتیب اولویت)</h3><ol class="steps">'
        + "".join(steps) + '</ol></div>'
        f'<details class="card gloss"><summary>📖 واژه‌نامه ساده (اصطلاح‌ها یعنی چه؟)</summary><dl>{gloss}</dl></details>'
    )
